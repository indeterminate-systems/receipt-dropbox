//! Generates `register_domains`, which registers every domain crate's ops, from this crate's
//! dependencies. A domain crate opts in with `[package.metadata.rdx] ops = true` and a
//! `pub fn register(&mut Registry)`; adding one to `rdx` is then a single dependency line in
//! Cargo.toml, with no list in the source for parallel pieces to collide on.

use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    let dir = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let manifest = dir.join("Cargo.toml");
    println!("cargo:rerun-if-changed={}", manifest.display());

    let deps = read(&manifest)
        .get("dependencies")
        .and_then(toml::Value::as_table)
        .cloned()
        .unwrap_or_default();

    let mut domains = Vec::new();
    for (name, spec) in &deps {
        let Some(path) = spec.get("path").and_then(toml::Value::as_str) else {
            continue;
        };
        let dep_manifest = dir.join(path).join("Cargo.toml");
        println!("cargo:rerun-if-changed={}", dep_manifest.display());
        if has_ops(&read(&dep_manifest)) {
            domains.push(name.replace('-', "_"));
        }
    }

    // A domain crate that isn't a dependency would silently be missing from `rdx`, so say so.
    let crates = dir.parent().unwrap();
    println!("cargo:rerun-if-changed={}", crates.display());
    let mut missing = Vec::new();
    for entry in fs::read_dir(crates).unwrap().flatten() {
        let m = entry.path().join("Cargo.toml");
        if m == manifest || !m.exists() {
            continue;
        }
        let doc = read(&m);
        let name = doc["package"]["name"].as_str().unwrap().to_owned();
        if has_ops(&doc) && !deps.contains_key(&name) {
            missing.push(name);
        }
    }
    if !missing.is_empty() {
        missing.sort();
        panic!(
            "domain crates with ops that rdx-cli doesn't depend on: {}. Add each to \
             [dependencies] in crates/rdx-cli/Cargo.toml, like `{0} = {{ path = \"../{0}\" }}`.",
            missing.join(", ")
        );
    }

    domains.sort();
    let calls: String = domains
        .iter()
        .map(|d| format!("    {d}::register(registry);\n"))
        .collect();
    let code = format!(
        "/// Registers the ops of every domain crate `rdx` depends on (generated by build.rs).\n\
         fn register_domains(registry: &mut rdx_plan::Registry) {{\n{calls}}}\n"
    );
    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap()).join("domains.rs");
    fs::write(out, code).unwrap();
}

fn read(path: &Path) -> toml::Table {
    let text = fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    text.parse()
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

fn has_ops(manifest: &toml::Table) -> bool {
    manifest
        .get("package")
        .and_then(|p| p.get("metadata"))
        .and_then(|m| m.get("rdx"))
        .and_then(|r| r.get("ops"))
        .and_then(toml::Value::as_bool)
        .unwrap_or(false)
}
